#!/usr/bin/env python3
"""Independent reference implementation of docs/protocol.md.

Writes docs/test-vectors.json. The Android (Kotlin/Tink) and macOS
(Swift/CryptoKit) implementations both test against this file, so a mismatch
between either of them and the spec shows up as a failing test on that side.

Requires: pip install cryptography
"""
import base64
import hashlib
import hmac
import json
import pathlib

from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PrivateKey
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.hkdf import HKDF
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat


def h(b: bytes) -> str:
    return b.hex()


def b64url(b: bytes) -> str:
    return base64.urlsafe_b64encode(b).rstrip(b"=").decode()


def pub(priv: bytes) -> bytes:
    return X25519PrivateKey.from_private_bytes(priv).public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)


def session_key(my_priv: bytes, peer_pub: bytes, mac_pub: bytes, phone_pub: bytes) -> tuple[bytes, bytes]:
    from cryptography.hazmat.primitives.asymmetric.x25519 import X25519PublicKey

    shared = X25519PrivateKey.from_private_bytes(my_priv).exchange(X25519PublicKey.from_public_bytes(peer_pub))
    k = HKDF(algorithm=hashes.SHA256(), length=32, salt=b"wifi-bridge/v1", info=mac_pub + phone_pub).derive(shared)
    return shared, k


def seal(k: bytes, nonce: bytes, aad: bytes, pt: bytes) -> bytes:
    return nonce + ChaCha20Poly1305(k).encrypt(nonce, pt, aad)


def frames(msg: bytes, chunk: int) -> list[bytes]:
    parts = [msg[i : i + chunk] for i in range(0, len(msg), chunk)] or [b""]
    out = []
    for i, p in enumerate(parts):
        hdr = (0x01 if i == 0 else 0) | (0x02 if i == len(parts) - 1 else 0)
        out.append(bytes([hdr]) + p)
    return out


def main() -> None:
    mac_priv = bytes(range(1, 33))
    phone_priv = bytes(range(101, 133))
    mac_pub, phone_pub = pub(mac_priv), pub(phone_priv)
    mac_id = bytes.fromhex("00112233445566778899aabbccddeeff")
    phone_id = bytes.fromhex("ffeeddccbbaa99887766554433221100")

    shared, k = session_key(mac_priv, phone_pub, mac_pub, phone_pub)
    shared2, k2 = session_key(phone_priv, mac_pub, mac_pub, phone_pub)
    assert (shared, k) == (shared2, k2)

    pair_secret = bytes.fromhex("0f0e0d0c0b0a09080706050403020100")
    mac_name = "Jaga’s MacBook"
    qr = ";".join(["WBPAIR1", b64url(mac_id), b64url(mac_pub), b64url(pair_secret), b64url(mac_name.encode())])
    proof = hmac.new(pair_secret, b"wb-pair-phone" + mac_id + phone_id + phone_pub, hashlib.sha256).digest()

    info = bytes([1]) + phone_id + phone_pub

    n1 = bytes.fromhex("a1a2a3a4a5a6a7a8a9aaabac")
    confirm_aad = b"wb-pair-confirm" + mac_id + phone_id
    confirm_box = seal(k, n1, confirm_aad, mac_name.encode())
    pair_confirm = bytes([0x03]) + mac_id + confirm_box

    req_json = '{"n":"AAECAwQFBgcICQoLDA0ODw","ssids":["Casita_Guest","Café ☕"],"all":false}'
    n2 = bytes.fromhex("b1b2b3b4b5b6b7b8b9babbbc")
    req_aad = b"wb-req" + mac_id + phone_id
    req_box = seal(k, n2, req_aad, req_json.encode())
    sync_request = bytes([0x10]) + mac_id + req_box

    resp_json = (
        '{"n":"AAECAwQFBgcICQoLDA0ODw","status":"ok","networks":'
        '[{"ssid":"Casita_Guest","security":"WPA","password":"p@ss;word","hidden":false}]}'
    )
    n3 = bytes.fromhex("c1c2c3c4c5c6c7c8c9cacbcc")
    resp_aad = b"wb-resp" + mac_id + phone_id
    resp_box = seal(k, n3, resp_aad, resp_json.encode())
    sync_response = bytes([0x11]) + resp_box

    vectors = {
        "_comment": "Generated by scripts/gen_test_vectors.py from docs/protocol.md. Do not edit by hand.",
        "keys": {
            "macPriv": h(mac_priv), "macPub": h(mac_pub),
            "phonePriv": h(phone_priv), "phonePub": h(phone_pub),
            "macId": h(mac_id), "phoneId": h(phone_id),
            "shared": h(shared), "K": h(k),
        },
        "info": h(info),
        "pairing": {
            "pairSecret": h(pair_secret), "macName": mac_name, "qr": qr,
            "qrUri": "wifibridge://pair?p=" + qr,
            "proof": h(proof), "pairRequest": h(bytes([0x01]) + mac_id), "pairAccept": h(bytes([0x02]) + proof),
            "confirmNonce": h(n1), "pairConfirm": h(pair_confirm),
        },
        "sync": {
            "requestJson": req_json, "requestNonce": h(n2), "syncRequest": h(sync_request),
            "responseJson": resp_json, "responseNonce": h(n3), "syncResponse": h(sync_response),
            "tamperedSyncResponse": h(sync_response[:-1] + bytes([sync_response[-1] ^ 1])),
        },
        "framing": [
            {"message": h(m), "chunk": c, "frames": [h(f) for f in frames(m, c)]}
            for m, c in [
                (bytes(range(50)), 19),
                (bytes(range(19)), 19),
                (bytes(range(20)), 19),
                (bytes([0x04]), 182),
            ]
        ],
        # Wi-Fi network QR payloads (as rendered by Android's "Share network").
        "wifiQr": [
            {"in": "WIFI:S:Casita_Guest;T:WPA;P:hunter22;H:false;;",
             "out": {"ssid": "Casita_Guest", "security": "WPA", "password": "hunter22", "hidden": False}},
            {"in": "WIFI:T:WPA;S:Casita_Guest;P:hunter22;;",
             "out": {"ssid": "Casita_Guest", "security": "WPA", "password": "hunter22", "hidden": False}},
            {"in": r"WIFI:S:My\;Net\:1;T:SAE;P:a\\b\;c\,d\"e;H:true;;",
             "out": {"ssid": "My;Net:1", "security": "SAE", "password": 'a\\b;c,d"e', "hidden": True}},
            {"in": "WIFI:S:Open Cafe;T:nopass;;",
             "out": {"ssid": "Open Cafe", "security": "nopass", "password": "", "hidden": False}},
            {"in": "WIFI:S:NoType;P:secret;;",
             "out": {"ssid": "NoType", "security": "WPA", "password": "secret", "hidden": False}},
            {"in": "WIFI:T:WEP;S:Old;P:abcde;;",
             "out": {"ssid": "Old", "security": "WEP", "password": "abcde", "hidden": False}},
            {"in": "wifi:s:lower;t:wpa;p:x;;",
             "out": {"ssid": "lower", "security": "WPA", "password": "x", "hidden": False}},
            {"in": "https://example.com", "out": None},
            {"in": "WIFI:T:WPA;P:nossid;;", "out": None},
        ],
    }
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "test-vectors.json"
    out.write_text(json.dumps(vectors, indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
